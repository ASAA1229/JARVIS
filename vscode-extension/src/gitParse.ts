import { isExcludedPath } from './redact';
import { matchesExclude, head } from './episodes';

export interface ParsedCommit {
  hash: string;
  message: string;
  files: Array<{ path: string; insertions: number; deletions: number }>;
}

/** Parses `git show --numstat --format=%H%x1e%B%x1e HEAD`. */
export function parseGitShow(output: string): ParsedCommit | undefined {
  const [hash, message, rest] = output.split('\x1e');
  if (!hash || !/^[0-9a-f]{7,64}$/i.test(hash.trim())) return undefined;
  const files = (rest ?? '').split('\n').flatMap((line) => {
    const match = /^(\d+|-)\t(\d+|-)\t(.+)$/.exec(line.trim());
    if (!match) return [];
    const path = match[3]!.includes(' => ') ? match[3]!.replace(/^.*=> |\}$/g, '') : match[3]!;
    return [{ path, insertions: match[1] === '-' ? 0 : Number(match[1]), deletions: match[2] === '-' ? 0 : Number(match[2]) }];
  });
  return { hash: hash.trim(), message: (message ?? '').trim(), files };
}

/** Drops diff sections of excluded files and truncates to maxBytes. */
export function filterDiff(patch: string, excludePaths: readonly string[], maxBytes: number): string {
  if (maxBytes <= 0) return '';
  const sections = patch.split(/^(?=diff --git )/m).filter(Boolean);
  const kept = sections.filter((section) => {
    const match = /^diff --git a\/(.+?) b\/(.+)$/m.exec(section);
    const path = match?.[2] ?? '';
    return !path || !(isExcludedPath(path) || matchesExclude(path, excludePaths));
  });
  return head(kept.join(''), maxBytes);
}

/** Commits co-authored or generated by an AI assistant carry assistantGenerated content. */
export function isAssistantCommit(message: string): boolean {
  return /co-authored-by:[^\n]*(claude|copilot|gpt|chatgpt|gemini|cursor|codex|openai|anthropic)|generated with \[?claude|generated by (copilot|chatgpt)/i.test(message);
}
